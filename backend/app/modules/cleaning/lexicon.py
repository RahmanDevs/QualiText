def normalize_id_stem(word: str) -> set[str]:
    """Generate candidate Indonesian root stems from an inflected/reduplicated word."""
    w = word.lower().strip("'-")
    if not w:
        return set()
    candidates: set[str] = {w}
    if "-" in w:
        for part in w.split("-"):
            if part:
                candidates.update(normalize_id_stem(part))

    queue = list(candidates)
    for base in queue:
        for suf in _ID_SUFFIXES:
            if base.endswith(suf) and len(base) - len(suf) >= 3:
                candidates.add(base[: -len(suf)])

    with_suffixes = list(candidates)
    for base in with_suffixes:
        for pref, restore in _ID_PREFIX_RULES:
            if base.startswith(pref) and len(base) - len(pref) + len(restore) >= 3:
                stem = restore + base[len(pref) :]
                candidates.add(stem)
                for suf in _ID_SUFFIXES:
                    if stem.endswith(suf) and len(stem) - len(suf) >= 3:
                        candidates.add(stem[: -len(suf)])
    return candidates


def normalize_en_stem(word: str) -> set[str]:
    """Generate candidate English root stems from an inflected word."""
    w = word.lower().strip("'-")
    if not w:
        return set()
    candidates: set[str] = {w}
    if w.endswith("'s") and len(w) > 3:
        candidates.add(w[:-2])
    if w.endswith("ies") and len(w) > 4:
        candidates.add(w[:-3] + "y")
    if w.endswith("ied") and len(w) > 4:
        candidates.add(w[:-3] + "y")
    if w.endswith("ing") and len(w) > 5:
        stem = w[:-3]
        candidates.add(stem)
        candidates.add(stem + "e")
        if len(stem) >= 2 and stem[-1] == stem[-2]:
            candidates.add(stem[:-1])
    if w.endswith("ed") and len(w) > 4:
        stem = w[:-2]
        candidates.add(stem)
        candidates.add(stem + "e")
        if len(stem) >= 2 and stem[-1] == stem[-2]:
            candidates.add(stem[:-1])
    if w.endswith("es") and len(w) > 4:
        candidates.add(w[:-2])
    if w.endswith("s") and len(w) > 3:
        candidates.add(w[:-1])
    for suf in ("tion", "ment", "ness", "ity", "able", "ible", "ly", "al", "er", "est"):
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            stem = w[: -len(suf)]
            candidates.add(stem)
            candidates.add(stem + "e")
    return candidates


def is_known_word(word: str, extra_vocab: frozenset[str] = frozenset()) -> bool:
    """Return True when `word` or its ID/EN stem matches built-in or custom vocabularies."""
    w = word.lower().strip("'-")
    if not w:
        return False
    if w in extra_vocab or w in TECH_COMMON_VOCAB or w in ID_BASE_VOCAB or w in EN_BASE_VOCAB:
        return True
    for stem in normalize_id_stem(w):
        if stem in ID_BASE_VOCAB or stem in extra_vocab or stem in TECH_COMMON_VOCAB:
            return True
    for stem in normalize_en_stem(w):
        if stem in EN_BASE_VOCAB or stem in extra_vocab or stem in TECH_COMMON_VOCAB:
            return True
    return False


